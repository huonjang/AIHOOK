"""Grounded, deterministic observations for invoice tool results.

These sentences may contain numbers because every number is computed from read-only
backend results, not generated by the LLM. They are not legal/accounting advice.
"""
from __future__ import annotations

from datetime import date
from decimal import Decimal, ROUND_HALF_UP
from typing import Any

CENT = Decimal('0.01')


def _amount(value: Any) -> Decimal:
    return Decimal(str(value or '0'))


def _vnd(value: Any) -> str:
    return f'{_amount(value):,.0f}'.replace(',', '.') + ' đ'


def _pct(numerator: Decimal, denominator: Decimal) -> str:
    if not denominator:
        return 'không xác định'
    return f'{(numerator / denominator * 100).quantize(CENT, rounding=ROUND_HALF_UP):.2f}%'


def _period_name(value: str) -> str:
    year, month = value.split('-')
    return f'tháng {int(month)}/{year}'


def build_observations(
    results: list[tuple[str, dict]],
    *,
    today: date | None = None,
) -> list[str]:
    """Return a few verified, question-relevant insights without hallucinating.

    Do not infer revenue, expense, profit, payment status, supplier quality or
    fraud from total invoice values alone.
    """
    today = today or date.today()
    observations: list[str] = []
    seen: set[str] = set()

    def add(message: str) -> None:
        if message and message not in seen:
            observations.append(message)
            seen.add(message)

    for name, result in results:
        if not isinstance(result, dict) or 'error' in result:
            continue
        if name == 'get_invoice_overview':
            overview = result['overview']
            n = int(overview['invoice_count'])
            if not n:
                add('Chưa có hóa đơn đã xác nhận trong phạm vi này; chưa thể nhận xét xu hướng hay nhà cung cấp.')
            else:
                add(f'Dữ liệu gồm {n} hóa đơn đã xác nhận, với tổng giá trị {_vnd(overview["total_amount"])}; trung bình {_vnd(overview["average_amount"])} mỗi hóa đơn.')
                missing = int(overview['undated_count'])
                if missing:
                    add(f'Có {missing} hóa đơn thiếu ngày lập; chúng không được phân bổ vào thống kê theo tháng và cần được kiểm tra lại.')
                else:
                    add('Các hóa đơn trong phạm vi này đều có ngày lập, nên có thể đối chiếu đầy đủ với thống kê theo tháng.')

        elif name == 'get_monthly_summary':
            rows = [r for r in result.get('monthly', []) if int(r['invoice_count']) > 0]
            if not rows:
                add('Không có hóa đơn có ngày lập trong phạm vi này để nhận xét theo tháng.')
                continue
            biggest = max(rows, key=lambda r: (_amount(r['total_amount']), r['month']))
            add(f'{_period_name(biggest["month"])} có tổng giá trị hóa đơn lớn nhất trong các tháng có dữ liệu: {_vnd(biggest["total_amount"])} từ {biggest["invoice_count"]} hóa đơn.')
            if len(rows) > 1:
                lowest = min(rows, key=lambda r: (_amount(r['total_amount']), r['month']))
                add(f'{_period_name(lowest["month"])} có tổng giá trị thấp nhất: {_vnd(lowest["total_amount"])}; cần kiểm tra tháng này có đủ dữ liệu cả kỳ trước khi kết luận xu hướng.')
                ordered = sorted(rows, key=lambda r: r['month'])
                first, last = ordered[0], ordered[-1]
                if _amount(first['total_amount']) == _amount(last['total_amount']):
                    movement = 'không thay đổi'
                else:
                    movement = 'cao hơn' if _amount(last['total_amount']) > _amount(first['total_amount']) else 'thấp hơn'
                add(f'So với {_period_name(first["month"])}, tổng giá trị ở {_period_name(last["month"])} {movement}; đây là so sánh hai mốc, không đủ để khẳng định xu hướng tăng/giảm liên tục.')
            if result.get('monthly_truncated'):
                add('Bảng theo tháng đã bị giới hạn số dòng; nhận xét chỉ áp dụng cho các tháng được trả về.')
            if any(r['month'] == today.strftime('%Y-%m') for r in rows):
                add(f'Dữ liệu {_period_name(today.strftime("%Y-%m"))} chưa chắc bao gồm cả tháng vì hiện mới đến ngày {today.strftime("%d/%m/%Y")}; tránh so sánh trực tiếp với tháng đã hoàn tất.')

        elif name == 'get_supplier_summary':
            rows = result.get('suppliers', [])
            if not rows:
                add('Chưa có dữ liệu nhà cung cấp để so sánh.')
                continue
            sort_by = result.get('sort_by', 'amount')
            head = rows[0]
            if sort_by == 'amount':
                add(f'{head["seller_name"]} dẫn đầu về tổng giá trị hóa đơn: {_vnd(head["total_amount"])} ({head["share_percent"]}% tổng giá trị), từ {head["invoice_count"]} hóa đơn.')
                if len(rows) >= 3:
                    total = _amount(result['total_amount'])
                    top3_total = sum((_amount(r['total_amount']) for r in rows[:3]), Decimal('0'))
                    add(f'Ba nhà cung cấp có tổng giá trị lớn nhất chiếm {_pct(top3_total, total)} tổng giá trị hóa đơn; đây là tỷ trọng giao dịch, chưa đủ để đánh giá chất lượng hay rủi ro nhà cung cấp.')
                frequent = max(rows, key=lambda r: (int(r['invoice_count']), _amount(r['total_amount'])))
                if frequent['seller_name'] != head['seller_name']:
                    add(f'{frequent["seller_name"]} xuất hiện nhiều nhất trong danh sách được trả về ({frequent["invoice_count"]} hóa đơn), nhưng không đứng đầu về tổng giá trị. Tần suất và giá trị là hai tiêu chí khác nhau.')
            else:
                add(f'{head["seller_name"]} có số lượng hóa đơn nhiều nhất trong danh sách: {head["invoice_count"]} hóa đơn, tổng giá trị {_vnd(head["total_amount"])}.')
                add('Xếp hạng này dựa trên tần suất, không phải tổng giá trị; để xác định nhà cung cấp lớn nhất về tiền cần xếp hạng theo giá trị.')

        elif name == 'compare_periods':
            a, b = result['period_a'], result['period_b']
            va, vb = _amount(a['total_amount']), _amount(b['total_amount'])
            ca, cb = int(a['invoice_count']), int(b['invoice_count'])
            sign = 'cao hơn' if vb > va else 'thấp hơn' if vb < va else 'bằng'
            pct = _pct(abs(vb-va), va)
            descriptor = f' ({pct} so với giai đoạn A)' if va else ' (không tính được tỷ lệ khi giai đoạn A bằng 0)'
            add(f'Giai đoạn B có tổng giá trị {sign} giai đoạn A { _vnd(abs(vb-va)) if vb != va else ""}{descriptor if vb != va else ""}.'.replace('  ', ' '))
            difference = cb - ca
            add(f'Số hóa đơn giai đoạn B {"nhiều hơn" if difference > 0 else "ít hơn" if difference < 0 else "bằng"} giai đoạn A' + (f' {abs(difference)} hóa đơn.' if difference else '.'))
            if ca and cb:
                avg_a, avg_b = _amount(a['average_amount']), _amount(b['average_amount'])
                if avg_a != avg_b:
                    add(f'Giá trị trung bình mỗi hóa đơn ở giai đoạn B {"cao hơn" if avg_b > avg_a else "thấp hơn"} giai đoạn A ({_vnd(avg_b)} so với {_vnd(avg_a)}).')
            add('Chênh lệch giá trị hóa đơn không đồng nghĩa doanh thu, chi phí hay lợi nhuận thay đổi khi chưa phân loại hóa đơn đầu vào/đầu ra.')

        elif name == 'get_invoice_details':
            if not result.get('found'):
                add('Không tìm thấy hóa đơn phù hợp trong phạm vi hiện tại; không thể kết luận nội dung hóa đơn đó.')
            else:
                rows = result.get('invoices', [])
                head = rows[0]
                add(f'Hóa đơn {head.get("invoice_number") or "ID " + str(head["invoice_id"])} thuộc nhà cung cấp {head.get("seller_name") or "chưa xác định"}, có tổng giá trị {_vnd(head.get("total_amount"))}.')
                missing = [
                    label for field, label in [('buyer_name', 'người mua'), ('subtotal', 'tiền trước thuế'), ('tax_amount', 'tiền thuế')]
                    if head.get(field) is None
                ]
                if missing:
                    add(f'Các trường {", ".join(missing)} chưa có dữ liệu trong hệ thống; cần xem bản hóa đơn gốc nếu muốn kiểm tra.')
                if not result.get('line_items_available'):
                    add('Hệ thống chưa lưu chi tiết từng mặt hàng, số lượng và đơn giá; AI không thể xác minh các thông tin đó.')
                if len(rows) > 1:
                    add('Có nhiều bản ghi trùng mã hóa đơn; cần xác định đúng ID trước khi kết luận về một hóa đơn cụ thể.')

        elif name == 'search_invoices':
            matched = int(result.get('matched_count', 0))
            shown = int(result.get('returned_count', 0))
            if not matched:
                add('Không tìm thấy hóa đơn phù hợp trong phạm vi tìm kiếm; không được tự suy đoán hóa đơn thay thế.')
            else:
                add(f'Tìm được {matched} hóa đơn phù hợp và đang hiển thị {shown} hóa đơn theo bộ lọc; danh sách có thể bị giới hạn số kết quả.')
                if shown and result.get('invoices'):
                    row = result['invoices'][0]
                    add(f'Một hóa đơn trong kết quả là {row.get("invoice_number") or "ID " + str(row["invoice_id"])} của {row.get("seller_name") or "nhà cung cấp chưa rõ"}, tổng giá trị {_vnd(row["total_amount"])}.')

    return observations[:10]


def build_recommendations(question: str, results: list[tuple[str, dict]], *, max_items: int = 5) -> list[str]:
    """Contextual suggestions, deliberately not factual claims or predictions."""
    text = question.casefold()
    if not any(key in text for key in ('khuyến nghị', 'khuyen nghi', 'đề xuất', 'de xuat', 'nên', 'gợi ý', 'goi y', 'cải thiện', 'cai thien', 'báo cáo', 'bao cao')):
        return []
    names = {name for name, res in results if 'error' not in res}
    suggestions: list[str] = []
    if 'get_supplier_summary' in names:
        suggestions.append('Đối chiếu điều khoản, đơn giá và chất lượng thực tế với các nhà cung cấp có giá trị giao dịch lớn trước khi điều chỉnh mức độ hợp tác.')
        suggestions.append('Theo dõi riêng tỷ trọng giao dịch và số hóa đơn theo từng nhà cung cấp để tránh đánh đồng giá trị với tần suất.')
    if 'get_monthly_summary' in names or 'compare_periods' in names:
        suggestions.append('So sánh theo các tháng đã hoàn tất; ghi chú kỳ chưa kết thúc để tránh kết luận sai về xu hướng.')
    if 'get_invoice_overview' in names:
        suggestions.append('Duy trì bước xác nhận thông tin OCR và đối chiếu hóa đơn gốc trước khi dùng số liệu làm báo cáo.')
    if 'get_invoice_details' in names or 'search_invoices' in names:
        suggestions.append('Mở file nguồn và bổ sung dữ liệu chưa có nếu cần kiểm tra thuế, sản phẩm hoặc điều kiện thanh toán.')
    suggestions.append('Phân biệt hóa đơn mua vào và bán ra trước khi đánh giá doanh thu, chi phí hay lợi nhuận.')
    suggestions.append('Rà soát hóa đơn trùng, thông tin thiếu và giao dịch giá trị bất thường bằng các quy tắc kiểm soát độc lập.')
    # Avoid padding unrelated advice. If asked explicitly for five recommendations, provide five relevant ones.
    return list(dict.fromkeys(suggestions))[:max_items]
